"""
Makes a performance of the face for every spoken line of the town, from the line's own recording.

    Tools/make_town_faces.sh                         every recording under /Game/Town/Voices that has no face yet
    TOWN_FACES_ONLY=warden_loop,needle_counter       only these recordings
    TOWN_FACES_REDO=1                                made again where there is one
    TOWN_FACES_CALLS=1                               the Block caller's cries as well (call_NN): they are heard across
                                                     the square, not said in a talk, so no face is made for them without this
    TOWN_FACES_MOOD=Auto                             Auto (read from the voice), Neutral, Happy, Sad, Disgust, Anger, Surprise, Fear

The work is Epic's: the MetaHuman Animator plugin's speech-to-face, which listens to a recording and gives the movement of
a MetaHuman's mouth, jaw, brows and lids that goes with it (its own script for this is
Engine/Plugins/MetaHuman/MetaHumanAnimator/Content/Python/process_audio_performance.py). Nothing is generated by this
project. The plugin is turned on for this run only (-EnablePlugins=MetaHuman), since the game does not need it to play the result:
each face is an ordinary animation of the face's controls, saved beside its recording as Faces/<recording>_face, and the
game plays it on whoever says the line (ATownGameMode::SayTalkLine, AGutFighter::Speak).
"""

import os

import unreal

VOICES = "/Game/Town/Voices"
SKELETON = "/Game/Gut/Art/MetaHumans/Common/Face/Face_Archetype_Skeleton"

ONLY = [name for name in os.environ.get("TOWN_FACES_ONLY", "").split(",") if name]
REDO = bool(os.environ.get("TOWN_FACES_REDO"))
CALLS = bool(os.environ.get("TOWN_FACES_CALLS"))
MOOD = os.environ.get("TOWN_FACES_MOOD", "Auto")

MOODS = {"Auto": "AUTO_DETECT", "Neutral": "NEUTRAL", "Happy": "HAPPY", "Sad": "SAD", "Disgust": "DISGUST", "Anger": "ANGER",
         "Surprise": "SURPRISE", "Fear": "FEAR"}


def log(text):
    unreal.log("[make_town_faces] " + text)


def make(recording):
    """The face for one recording. Returns the animation, or None."""
    eal = unreal.EditorAssetLibrary

    folder = recording.get_path_name().rsplit("/", 1)[0] + "/Faces"
    name = recording.get_name() + "_face"
    path = folder + "/" + name

    if eal.does_asset_exist(path):
        if not REDO:
            return unreal.load_asset(path)

        eal.delete_asset(path)

    work = folder + "/Work"
    tools = unreal.AssetToolsHelpers.get_asset_tools()

    if eal.does_asset_exist(work + "/" + name + "_performance"):
        eal.delete_asset(work + "/" + name + "_performance")

    performance = tools.create_asset(asset_name=name + "_performance", package_path=work, asset_class=unreal.MetaHumanPerformance,
                                     factory=unreal.MetaHumanPerformanceFactoryNew())

    performance.set_editor_property("input_type", unreal.DataInputType.AUDIO)
    performance.set_editor_property("audio", recording)

    overrides = unreal.AudioDrivenAnimationSolveOverrides()
    overrides.mood = getattr(unreal.AudioDrivenAnimationMood, MOODS[MOOD])
    overrides.mood_intensity = 1.0

    performance.set_editor_property("audio_driven_animation_solve_overrides", overrides)
    performance.set_editor_property("audio_driven_animation_output_controls", unreal.AudioDrivenAnimationOutputControls.FULL_FACE)

    # the head's own nodding is left out: the body's clip has the head
    performance.set_editor_property("head_movement_mode", unreal.PerformanceHeadMovementMode.DISABLED)

    performance.set_blocking_processing(True)

    error = performance.start_pipeline()

    if error is not unreal.StartPipelineErrorType.NONE:
        log("{}: the pipeline did not start ({})".format(recording.get_name(), error))
        return None

    settings = unreal.MetaHumanPerformanceExportAnimationSettings()
    settings.show_export_dialog = False
    settings.package_path = folder
    settings.asset_name = name
    settings.target_skeleton_or_skeletal_mesh = unreal.load_asset(SKELETON)
    settings.enable_head_movement = False
    settings.export_range = unreal.PerformanceExportRange.PROCESSING_RANGE

    sequence = unreal.MetaHumanPerformanceExportUtils.export_animation_sequence(performance, settings)

    # the working asset is not kept: it holds nothing the animation does not
    eal.delete_directory(work)

    if not sequence:
        log("{}: nothing came out".format(recording.get_name()))
        return None

    eal.save_loaded_asset(sequence)

    return sequence


def main():
    registry = unreal.AssetRegistryHelpers.get_asset_registry()
    made = 0
    failed = []

    for data in registry.get_assets_by_path(VOICES, recursive=True):
        if "/Faces" in str(data.package_path) or (ONLY and str(data.asset_name) not in ONLY):
            continue

        if str(data.asset_name).startswith("call_") and not CALLS and not ONLY:
            continue

        recording = data.get_asset()

        if not isinstance(recording, unreal.SoundWave):
            continue

        sequence = make(recording)

        if sequence:
            made += 1
            log("{}: {:.1f} s of voice, {:.1f} s of face".format(recording.get_name(), recording.get_editor_property("duration"), sequence.get_play_length()))
        else:
            failed.append(str(data.asset_name))

    log("{} faces{}".format(made, "; none for: " + ", ".join(failed) if failed else ""))
    log("DONE")


main()
